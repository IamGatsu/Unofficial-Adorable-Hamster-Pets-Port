#!/usr/bin/env python3
"""Restores the original assets into src/main/resources ONLY FOR THE DATAGEN RUN.

Datagen (./gradlew runDatagen) needs textures/models/lang/en_us_base.json. Procedure:
    python tools/restore_assets.py <original.jar>     # restore assets (in the 26.2 layout)
    ./gradlew runDatagen                              # generates src/main/generated
    python tools/strip_assets.py <original.jar>       # remove them again before you commit/distribute

Only the paths from tools/asset_manifest.txt are written (the files the port had in the repo);
the many other models of the original are generated by datagen itself.
"""
import json, sys, zipfile
from pathlib import Path

if len(sys.argv) < 2:
    sys.exit(__doc__)
root = Path(__file__).resolve().parent.parent
res = root / "src" / "main" / "resources"
NS = "assets/adorablehamsterpets/"
manifest = [l.strip() for l in (root / "tools" / "asset_manifest.txt").read_text().splitlines() if l.strip()]

def source_name(rel):
    if rel.startswith(NS + "geckolib/models/"):
        return NS + "geo/" + rel[len(NS + "geckolib/models/"):]
    if rel.startswith(NS + "geckolib/animations/"):
        return NS + "animations/" + rel[len(NS + "geckolib/animations/"):]
    return rel

def transform(rel, data):
    # same adjustments as the Java transformers of the Asset Bridge
    if rel.startswith(NS + "lang/") and rel.endswith(".json"):
        o = json.loads(data)
        old, new = "key.categories.adorablehamsterpets.main", "key.category.adorablehamsterpets.main"
        if old in o and new not in o:
            o[new] = o[old]
            return json.dumps(o, ensure_ascii=False, indent=2).encode()
    if rel in (NS + "models/item/hamster_bed.json", NS + "models/item/upside_down_hamster_bed_icon.json"):
        o = json.loads(data)
        o.pop("parent", None)
        o["textures"] = {"particle": "adorablehamsterpets:block/hamster_bed_oak"}
        return json.dumps(o, indent=2).encode()
    return data

n = 0
with zipfile.ZipFile(sys.argv[1]) as z:
    for rel in manifest:
        target = res / rel
        if target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(transform(rel, z.read(source_name(rel))))
        n += 1
print(f"{n} Dateien wiederhergestellt. Danach: ./gradlew runDatagen, dann python tools/strip_assets.py <jar>")
